'use strict';

/**
 * Assembles the files that ship next to the Electron app.
 *
 * Everything the app spawns at runtime (the Express backend and the Next.js
 * standalone server) is a real child process, so it cannot live inside
 * app.asar — those files are copied into `build/` and packaged through
 * electron-builder's `extraResources`.
 *
 *   build/backend/    dist + production-only node_modules + uploads
 *   build/frontend/   Next.js standalone server + static + public
 *   build/config/     runtime config template (seeded into userData on first run)
 *
 * The real backend/.env is deliberately NOT copied: it holds database
 * credentials and would otherwise sit in plain sight inside the installer.
 * Its values are folded into build/config/app-config.json instead, and the
 * per-install JWT secret is generated by the app on first launch.
 *
 * Run through: npm run pack
 */

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const BUILD = path.join(ROOT, 'build');
const BACKEND_SRC = path.join(ROOT, 'backend');
const FRONTEND_SRC = path.join(ROOT, 'frontend');

const log = (msg) => console.log(`[pack] ${msg}`);

function rmrf(target) {
  fs.rmSync(target, { recursive: true, force: true });
}

function copy(from, to) {
  if (!fs.existsSync(from)) return false;
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.cpSync(from, to, { recursive: true });
  return true;
}

/** Reads a dotenv file into a plain object, tolerating quotes and comments. */
function readEnvFile(file) {
  const out = {};
  if (!fs.existsSync(file)) return out;

  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
    if (!match) continue;
    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[match[1]] = value;
  }

  return out;
}

// ── Backend ──────────────────────────────────────────────────────────────────

function packBackend() {
  const dest = path.join(BUILD, 'backend');

  if (!fs.existsSync(path.join(BACKEND_SRC, 'dist', 'index.js'))) {
    throw new Error('backend/dist/index.js is missing — run `npm run build:backend` first.');
  }

  log('packing backend (dist + production dependencies)…');
  fs.mkdirSync(dest, { recursive: true });

  for (const file of ['package.json', 'package-lock.json']) {
    const src = path.join(BACKEND_SRC, file);
    if (fs.existsSync(src)) fs.copyFileSync(src, path.join(dest, file));
  }

  copy(path.join(BACKEND_SRC, 'dist'), path.join(dest, 'dist'));

  // Uploads are user data (shop logo, avatars). Ship whatever exists so an
  // existing install keeps its branding after an upgrade.
  copy(path.join(BACKEND_SRC, 'uploads'), path.join(dest, 'uploads'));
  fs.mkdirSync(path.join(dest, 'uploads'), { recursive: true });

  // Production-only dependencies. `npm ci --omit=dev` is tried first because it
  // is much faster; if the registry is unreachable, copying the existing tree
  // and pruning it keeps the build working fully offline.
  const npmCmd = process.platform === 'win32' ? 'npm.cmd' : 'npm';
  let installed = false;

  try {
    log('installing production dependencies (npm ci --omit=dev)…');
    execFileSync(npmCmd, ['ci', '--omit=dev', '--prefer-offline', '--no-audit', '--no-fund'], {
      cwd: dest,
      stdio: 'inherit',
    });
    installed = true;
  } catch {
    log('npm ci failed — falling back to copying the existing node_modules…');
  }

  if (!installed) {
    copy(path.join(BACKEND_SRC, 'node_modules'), path.join(dest, 'node_modules'));
    try {
      execFileSync(npmCmd, ['prune', '--omit=dev', '--no-audit', '--no-fund'], {
        cwd: dest,
        stdio: 'inherit',
      });
    } catch {
      log('npm prune failed — shipping node_modules as-is.');
    }
  }

  const hasExpress = fs.existsSync(path.join(dest, 'node_modules', 'express', 'package.json'));
  if (!hasExpress) {
    throw new Error('backend production dependencies are incomplete (express is missing).');
  }

  log('backend packed.');
}

// ── Frontend ─────────────────────────────────────────────────────────────────

function packFrontend() {
  const standalone = path.join(FRONTEND_SRC, '.next', 'standalone');
  const dest = path.join(BUILD, 'frontend');

  if (!fs.existsSync(path.join(standalone, 'server.js'))) {
    throw new Error(
      'frontend/.next/standalone/server.js is missing — run `npm run build:frontend` first ' +
        '(next.config.mjs must keep output: "standalone").'
    );
  }

  log('packing frontend (Next.js standalone)…');
  copy(standalone, dest);

  // Next.js does not copy these two into the standalone folder itself.
  copy(path.join(FRONTEND_SRC, '.next', 'static'), path.join(dest, '.next', 'static'));
  copy(path.join(FRONTEND_SRC, 'public'), path.join(dest, 'public'));

  if (!fs.existsSync(path.join(dest, '.next', 'static'))) {
    throw new Error('frontend/.next/static is missing from the standalone bundle.');
  }

  log('frontend packed.');
}

// ── Local database engine ────────────────────────────────────────────────────

/**
 * The standalone mongod that keeps the shop selling offline. The folder is
 * always created so electron-builder's extraResources never points at a missing
 * path; without the binary the app simply runs against the cloud database.
 */
function packMongod() {
  const src = path.join(ROOT, 'electron', 'mongodb', 'bin');
  const dest = path.join(BUILD, 'mongodb', 'bin');
  fs.mkdirSync(dest, { recursive: true });

  const binary = path.join(src, 'mongod.exe');

  if (fs.existsSync(binary)) {
    for (const name of fs.readdirSync(src)) {
      fs.copyFileSync(path.join(src, name), path.join(dest, name));
    }
    log(`mongod bundled (${(fs.statSync(path.join(dest, 'mongod.exe')).size / 1048576).toFixed(1)}MB).`);
    return;
  }

  fs.writeFileSync(
    path.join(dest, 'README.txt'),
    'No mongod.exe was bundled with this build.\n\n' +
      'The app will run against the cloud database only (no offline mode).\n' +
      'To enable offline mode, run `npm run fetch:mongod` before packaging.\n'
  );
  log('mongod.exe not found — building a cloud-only app (run `npm run fetch:mongod` for offline mode).');
}

// ── Runtime config ───────────────────────────────────────────────────────────

function packConfig() {
  const dest = path.join(BUILD, 'config');
  fs.mkdirSync(dest, { recursive: true });

  const backendEnv = readEnvFile(path.join(BACKEND_SRC, '.env'));

  const config = {
    // Seeded into %APPDATA%/UniquePos/config.json on first launch. Note that a
    // credential shipped to a customer machine can always be extracted, so the
    // cloud database should use a dedicated low-privilege user.
    cloudMongoUri: backendEnv.MONGODB_URI || '',
    localMongoUri: 'mongodb://127.0.0.1:27017/pos_db',
    localMongoPort: 27017,
    backendPort: 5000,
    frontendPort: 3000,
    clientUrl: backendEnv.CLIENT_URL || 'http://localhost:3000',
    syncEnabled: true,
    syncIntervalSeconds: 60,
    hardware: {
      paperWidth: '80mm',
      printerName: '',
      cashDrawerOnReceipt: true,
      printMode: 'thermal',
      documentPrinterName: '',
      paperSize: 'A4',
      showPrintDialog: false,
    },
  };

  fs.writeFileSync(path.join(dest, 'app-config.json'), JSON.stringify(config, null, 2));
  log('runtime config template written (build/config/app-config.json).');
}

// ── Main ─────────────────────────────────────────────────────────────────────

function main() {
  log(`cleaning ${BUILD}`);
  rmrf(BUILD);
  fs.mkdirSync(BUILD, { recursive: true });

  packBackend();
  packFrontend();
  packMongod();
  packConfig();

  log('done — now run: npx electron-builder --win');
}

main();
